import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {writeFileSync} from 'node:fs';
const require=createRequire(new URL('../frontend/package.json',import.meta.url));
const {build}=require('esbuild');
async function load(name){const r=await build({entryPoints:[new URL(`../frontend/src/${name}.ts`,import.meta.url).pathname],bundle:true,write:false,format:'esm',platform:'node'});return import(`data:text/javascript;base64,${Buffer.from(r.outputFiles[0].text).toString('base64')}`);}
const {transmissionLineTemplate,bassReflexTemplate}=await load('topologyTemplates');
const {buildModelDict}=await load('translator');
const {stuffingZones}=await load('stuffing');
const {scaleSensitivity,dragValue}=await load('tuningGesture');
const {parametersFor,boxSummary}=await load('parameters');
const {assessGraphCompilability}=await load('graphCompilability');
const slow=scaleSensitivity({mode:'relative',step:2},.5);
assert(Math.abs(dragValue(10,200,200,slow,false)-10*Math.sqrt(2))<1e-10);
assert(Math.abs(scaleSensitivity(slow,2).step-2)<1e-10);
assert.equal(scaleSensitivity({mode:'absolute',step:2},.5).step,1);
const graph=structuredClone(transmissionLineTemplate),line=graph.nodes.find(n=>n.data.type==='waveguide_1d');
Object.assign(line.data,{areaCm2:100,mouthAreaCm2:200,lengthCm:200,driverOffsetCm:40,stuffing1Start:0,stuffing1End:25,stuffing1Density:15});
assert.match(boxSummary(graph.nodes,'transmission_line'),/30.00 L/);
assert(assessGraphCompilability({topology:'transmission_line',...graph,seedGraph:transmissionLineTemplate}).canRunSimulation);
const model=buildModelDict(graph.nodes,graph.edges),sections=model.elements.filter(e=>e.type==='waveguide_1d');
assert.equal(sections.length,3);assert.equal(sections.reduce((s,e)=>s+parseFloat(e.length),0),200);
assert.equal(sections[0].node_b,'rear');assert.equal(sections[1].node_a,'rear');
assert(sections[0].flow_resistivity>0&&sections[1].flow_resistivity>0);assert(!sections[2].flow_resistivity);
assert.equal(parseFloat(sections[2].area_end),200);
for(const [key,value] of [['stuffing1End',101],['stuffing1Start',26],['stuffingReferenceDensity',0],['stuffing1Density',-1]]) assert.throws(()=>stuffingZones({...line.data,[key]:value}));
assert.throws(()=>stuffingZones({...line.data,stuffing2Start:20,stuffing2Density:20}),/overlap/);
const half=stuffingZones(line.data)[0].resistivity;
assert(stuffingZones({...line.data,stuffing1Density:30})[0].resistivity>half);
const groups=new Set(parametersFor(graph.nodes,'transmission_line').map(p=>p.group));assert.deepEqual([...groups].sort(),['Amplifier','Box','Loudspeaker']);
const br=structuredClone(bassReflexTemplate);br.nodes.find(n=>n.data.type==='driver').data.series_resistance_ohm=2;
assert.equal(buildModelDict(br.nodes,br.edges).driver.series_resistance_ohm,2);
writeFileSync('/tmp/oslem-stuffed-test.json',JSON.stringify(model));
console.log('PASS: sensitivity scaling; group coverage; taper volume; zone geometry, offset splitting, resistivity scaling and validation; amplifier export.');
